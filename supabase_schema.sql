-- Run this entire script in Supabase Dashboard -> SQL Editor -> New query.
create table if not exists public.patients (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 1 and 100),
  age integer not null check (age between 0 and 120),
  gender text not null check (gender in ('Female', 'Male', 'Other')),
  phone text not null check (char_length(phone) between 1 and 20),
  address text not null check (char_length(address) between 1 and 250),
  blood_group text not null check (blood_group in ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-', 'Unknown')),
  symptoms text not null check (char_length(symptoms) between 1 and 300),
  registered_at timestamptz not null default now()
);

-- The API uses the service-role key only on the server. Do not put that key in frontend files.
-- Keep Row Level Security enabled; the server API bypasses RLS using the server-only service-role key.
alter table public.patients enable row level security;
